import { NextRequest, NextResponse } from 'next/server';
import { fetchTranscript, listLanguages } from 'youtube-transcript-plus';
import ytSearch from 'yt-search';

interface LrcLibTrack {
  id: number;
  name: string;
  trackName: string;
  artistName: string;
  albumName?: string;
  duration?: number;
  instrumental: boolean;
  plainLyrics?: string;
  syncedLyrics?: string;
}

export interface LyricSegment {
  time: number;
  duration: number;
  text: string;
}

interface CachedLyrics {
  data: {
    trackName: string;
    artistName: string;
    syncedLyrics?: string;
    plainLyrics?: string;
    segments?: LyricSegment[];
    instrumental: boolean;
    source: 'youtube' | 'lrclib';
    lang?: string;
  } | null;
  timestamp: number;
}

// In-memory cache với giới hạn tối đa 300 bài
const lyricsCache = new Map<string, CachedLyrics>();
const CACHE_TTL_MS = 1000 * 60 * 60 * 24; // 24 giờ
const MAX_CACHE_SIZE = 300;

function decodeHtmlEntities(str: string): string {
  if (!str) return '';
  return str
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .trim();
}

function cleanString(str: string): string {
  if (!str) return '';
  return str
    .replace(/[\(\[\{](official\s*(music)?\s*(video|audio)|mv|lyric\s*video|visualizer|audio|prod\.[^)\],]+|ft\.[^)\],]+|feat\.[^)\],]+|4k|hd|1080p|remix|cover)[\)\]\}]/gi, '')
    .replace(/\|\s*official\s*(music)?\s*(video|audio)?/gi, '')
    .replace(/[\(\[\{]\s*[\)\]\}]/g, '')
    .trim();
}

function parseArtistAndTitle(rawTitle: string, rawArtist: string) {
  let title = rawTitle.trim();
  let artist = (rawArtist || '').trim();

  const isGenericArtist = !artist || /^(nghệ sĩ chưa rõ|unknown artist|youtube|soundcloud)$/i.test(artist);

  if (title.includes(' - ')) {
    const parts = title.split(' - ');
    if (parts.length >= 2) {
      if (isGenericArtist) {
        artist = parts[0].trim();
      }
      title = parts.slice(1).join(' - ').trim();
    }
  }

  title = cleanString(title);
  artist = cleanString(artist);

  return { title, artist };
}

/**
 * Trích xuất phụ đề chính thức chuẩn từng giây từ YouTube (YouTube Captions / Subtitles)
 */
async function getYouTubeSubtitles(videoId: string): Promise<{
  segments: LyricSegment[];
  syncedLyrics: string;
  plainLyrics: string;
  lang: string;
} | null> {
  try {
    const languages = await listLanguages(videoId);
    if (!languages || languages.length === 0) return null;

    // Ưu tiên:
    // 1. Tiếng Việt manual
    // 2. Tiếng Anh manual
    // 3. Tiếng Việt auto
    // 4. Bất kỳ manual
    // 5. Tiếng Anh auto
    // 6. Ngôn ngữ đầu tiên
    const viManual = languages.find((l) => l.languageCode.startsWith('vi') && !l.isAutoGenerated);
    const enManual = languages.find((l) => l.languageCode.startsWith('en') && !l.isAutoGenerated);
    const viAuto = languages.find((l) => l.languageCode.startsWith('vi') && l.isAutoGenerated);
    const anyManual = languages.find((l) => !l.isAutoGenerated);
    const enAuto = languages.find((l) => l.languageCode.startsWith('en') && l.isAutoGenerated);

    const selected = viManual || enManual || viAuto || anyManual || enAuto || languages[0];
    const langCode = selected?.languageCode;

    const transcript = langCode
      ? await fetchTranscript(videoId, { lang: langCode })
      : await fetchTranscript(videoId);
    if (!transcript || transcript.length === 0) return null;

    const segments: LyricSegment[] = [];
    const lrcLines: string[] = [];
    const plainLines: string[] = [];

    for (const item of transcript) {
      const text = decodeHtmlEntities(item.text).replace(/\n/g, ' ').trim();
      // Bỏ qua các nhãn ký hiệu âm thanh phụ như [Nhạc], [Music], [♪♪♪] nếu đứng 1 mình
      if (!text || /^(\[|\()(nhạc|âm nhạc|music|applause|vỗ tay|tiếng vỗ tay|♪+)(\]|\))$/i.test(text)) {
        continue;
      }

      const totalSec = Math.max(0, item.offset);
      const dur = Math.max(0.5, item.duration || 2.0);

      segments.push({
        time: totalSec,
        duration: dur,
        text,
      });

      const m = Math.floor(totalSec / 60).toString().padStart(2, '0');
      const s = Math.floor(totalSec % 60).toString().padStart(2, '0');
      const ms = Math.floor((totalSec % 1) * 100).toString().padStart(2, '0');

      lrcLines.push(`[${m}:${s}.${ms}] ${text}`);
      plainLines.push(text);
    }

    if (segments.length === 0) return null;

    return {
      segments,
      syncedLyrics: lrcLines.join('\n'),
      plainLyrics: plainLines.join('\n'),
      lang: selected.languageCode,
    };
  } catch {
    return null;
  }
}

export async function GET(request: NextRequest) {
  try {
    const { searchParams } = new URL(request.url);
    const rawTitle = searchParams.get('title') || '';
    const rawArtist = searchParams.get('artist') || '';
    let videoId = searchParams.get('videoId') || '';
    const durationParam = searchParams.get('duration');
    const duration = durationParam ? Math.round(Number(durationParam)) : undefined;

    if (!rawTitle.trim() && !videoId.trim()) {
      return NextResponse.json({ error: 'Title or videoId is required' }, { status: 400 });
    }

    const { title, artist } = parseArtistAndTitle(rawTitle, rawArtist);
    const cacheKey = videoId ? `yt:${videoId}` : `${title.toLowerCase()}:::${artist.toLowerCase()}`;

    // 1. Kiểm tra Cache
    const cached = lyricsCache.get(cacheKey);
    if (cached && Date.now() - cached.timestamp < CACHE_TTL_MS) {
      return NextResponse.json({
        success: Boolean(cached.data),
        cached: true,
        lyrics: cached.data,
      });
    }

    let resultPayload: CachedLyrics['data'] = null;

    // 2. NẾU CHƯA CÓ videoId, THỬ TÌM TRÊN YOUTUBE ĐỂ LẤY videoId
    if (!videoId && title) {
      try {
        const query = `${title} ${artist}`.trim();
        const searchResult = await ytSearch(query);
        if (searchResult && searchResult.videos && searchResult.videos.length > 0) {
          videoId = searchResult.videos[0].videoId;
        }
      } catch {}
    }

    // 3. THỬ LẤY PHỤ ĐỀ TRỰC TIẾP TỪ YOUTUBE (Khớp 100% video YouTube, không lệch giây)
    if (videoId) {
      const ytSub = await getYouTubeSubtitles(videoId);
      if (ytSub) {
        resultPayload = {
          trackName: title || 'YouTube Track',
          artistName: artist || 'YouTube Artist',
          syncedLyrics: ytSub.syncedLyrics,
          plainLyrics: ytSub.plainLyrics,
          segments: ytSub.segments,
          instrumental: false,
          source: 'youtube',
          lang: ytSub.lang,
        };
      }
    }

    // 4. NẾU YOUTUBE KHÔNG CÓ PHỤ ĐỀ -> DỰ PHÒNG SANG LRCLIB API
    if (!resultPayload && title) {
      let foundLrcTrack: LrcLibTrack | null = null;

      // 4a. Exact match
      if (artist) {
        try {
          const getUrl = new URL('https://lrclib.net/api/get');
          getUrl.searchParams.set('track_name', title);
          getUrl.searchParams.set('artist_name', artist);
          if (duration && duration > 0) {
            getUrl.searchParams.set('duration', duration.toString());
          }

          const res = await fetch(getUrl.toString(), {
            headers: {
              'User-Agent': 'AuraSync-Desktop/1.0 (https://github.com/aurasync)',
            },
            signal: AbortSignal.timeout(4500),
          });

          if (res.ok) {
            const item = (await res.json()) as LrcLibTrack;
            if (item && (item.syncedLyrics || item.plainLyrics)) {
              foundLrcTrack = item;
            }
          }
        } catch {}
      }

      // 4b. Fuzzy search
      if (!foundLrcTrack) {
        try {
          const searchQuery = `${title} ${artist}`.trim();
          const searchUrl = new URL('https://lrclib.net/api/search');
          searchUrl.searchParams.set('q', searchQuery);

          const res = await fetch(searchUrl.toString(), {
            headers: {
              'User-Agent': 'AuraSync-Desktop/1.0 (https://github.com/aurasync)',
            },
            signal: AbortSignal.timeout(5000),
          });

          if (res.ok) {
            const list = (await res.json()) as LrcLibTrack[];
            if (Array.isArray(list) && list.length > 0) {
              const syncedWithDuration = list.find(
                (item) =>
                  item.syncedLyrics &&
                  (!duration || !item.duration || Math.abs(item.duration - duration) <= 12)
              );
              const anySynced = list.find((item) => Boolean(item.syncedLyrics));
              const anyPlain = list.find((item) => Boolean(item.plainLyrics));

              foundLrcTrack = syncedWithDuration || anySynced || anyPlain || list[0] || null;
            }
          }
        } catch {}
      }

      if (foundLrcTrack && (foundLrcTrack.syncedLyrics || foundLrcTrack.plainLyrics || foundLrcTrack.instrumental)) {
        resultPayload = {
          trackName: foundLrcTrack.trackName || foundLrcTrack.name || title,
          artistName: foundLrcTrack.artistName || artist,
          syncedLyrics: foundLrcTrack.syncedLyrics || undefined,
          plainLyrics: foundLrcTrack.plainLyrics || undefined,
          instrumental: Boolean(foundLrcTrack.instrumental),
          source: 'lrclib',
        };
      }
    }

    // 5. Lưu Cache
    if (lyricsCache.size >= MAX_CACHE_SIZE) {
      const firstKey = lyricsCache.keys().next().value;
      if (firstKey) lyricsCache.delete(firstKey);
    }
    lyricsCache.set(cacheKey, { data: resultPayload, timestamp: Date.now() });

    return NextResponse.json({
      success: Boolean(resultPayload),
      cached: false,
      lyrics: resultPayload,
    });
  } catch (error: any) {
    return NextResponse.json(
      { error: error?.message || 'Internal Server Error' },
      { status: 500 }
    );
  }
}
